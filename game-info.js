let gameInfoOpen=false,gameInfoSelection=null;
function gameInfoFileUrl(file){
  return file.type==="image"
    ?"https://drive.google.com/file/d/"+encodeURIComponent(file.id)+"/preview"
    :"https://docs.google.com/document/d/"+encodeURIComponent(file.id)+"/preview";
}
function gameInfoOriginalUrl(file){
  return file.type==="image"
    ?"https://drive.google.com/file/d/"+encodeURIComponent(file.id)+"/view"
    :"https://docs.google.com/document/d/"+encodeURIComponent(file.id)+"/view";
}
function gameInfoEscape(s){return String(s??"").replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]))}
function closeGameInfo(){
  document.getElementById("gameInfoOverlay")?.remove();
  document.removeEventListener("keydown",gameInfoKeydown);
  gameInfoOpen=false;
}
function gameInfoKeydown(e){if(e.key==="Escape")closeGameInfo()}
function gameInfoOpenFile(file,button){
  gameInfoSelection=file.id;
  const viewer=document.getElementById("gameInfoViewer");if(!viewer)return;
  document.querySelectorAll("#gameInfoOverlay .game-info-file").forEach(b=>b.classList.toggle("selected",b.dataset.fileId===file.id));
  viewer.innerHTML='<div class="game-info-viewer-head"><h3>'+gameInfoEscape(file.title)+'</h3>'+
    '<a class="game-info-external" href="'+gameInfoOriginalUrl(file)+'" target="_blank" rel="noopener noreferrer">Open in Google Drive ↗</a></div>'+
    '<div class="game-info-frame-wrap"><iframe title="'+gameInfoEscape(file.title)+'" src="'+gameInfoFileUrl(file)+'" allow="fullscreen" referrerpolicy="strict-origin-when-cross-origin"></iframe></div>'+
    '<p class="game-info-help">If the preview asks you to sign in or request access, the document’s Google Drive permissions need to allow your account.</p>';
  if(window.matchMedia("(max-width: 720px)").matches)viewer.scrollIntoView({behavior:"smooth",block:"start"});
}
function openGameInfo(){
  if(gameInfoOpen)return;
  gameInfoOpen=true;
  const overlay=document.createElement("div");
  overlay.id="gameInfoOverlay";overlay.className="game-info-overlay";
  const groupsHtml=GAME_INFO_GROUPS.map(group=>{
    const files=(group.items||[]).map(file=>({file,section:""})).concat(
      (group.sections||[]).flatMap(section=>section.items.map(file=>({file,section:section.name})))
    );
    return '<details class="game-info-category" '+(group.name==="General rules"?"open":"")+'><summary>'+gameInfoEscape(group.name)+' <small>'+files.length+'</small></summary>'+
      (group.sections||[]).map(section=>'<div class="game-info-subhead">'+gameInfoEscape(section.name)+'</div>'+
        section.items.map(file=>'<button type="button" class="game-info-file" data-file-id="'+file.id+'">'+gameInfoEscape(file.title)+'</button>').join("")).join("")+
      (group.items||[]).map(file=>'<button type="button" class="game-info-file" data-file-id="'+file.id+'">'+gameInfoEscape(file.title)+'</button>').join("")+
      '</details>';
  }).join("");
  overlay.innerHTML='<div class="game-info-modal paper" role="dialog" aria-modal="true" aria-label="Game Info">'+
    '<div class="game-info-top"><h2>Game Info</h2><button type="button" class="game-info-close" aria-label="Close Game Info">×</button></div>'+
    '<div class="game-info-layout"><nav class="game-info-nav" aria-label="Game information categories">'+groupsHtml+'</nav>'+
    '<section class="game-info-viewer" id="gameInfoViewer"><div class="game-info-placeholder"><h3>Choose a document</h3><p>Browse the categories to view rules, spells, towns, enemies, and art without leaving your character sheet.</p></div></section></div></div>';
  document.body.appendChild(overlay);
  overlay.onclick=e=>{if(e.target===overlay)closeGameInfo()};
  overlay.querySelector(".game-info-close").onclick=closeGameInfo;
  overlay.querySelectorAll(".game-info-file").forEach(button=>button.onclick=()=>{
    const file=GAME_INFO_GROUPS.flatMap(group=>[...(group.items||[]),...(group.sections||[]).flatMap(s=>s.items)]).find(f=>f.id===button.dataset.fileId);
    if(file)gameInfoOpenFile(file,button);
  });
  document.addEventListener("keydown",gameInfoKeydown);
  overlay.querySelector(".game-info-close").focus();
}
function initGameInfo(){
  if(document.getElementById("gameInfoButton"))return;
  const button=document.createElement("button");button.type="button";button.id="gameInfoButton";button.className="game-info-fab";
  button.textContent="📖 Game Info";button.onclick=openGameInfo;button.setAttribute("aria-label","Open Game Info");
  app.appendChild(button);
}
